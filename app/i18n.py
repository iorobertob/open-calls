def get_lang():
    lang = session.get("lang")
    if lang in ("lt", "en"):
        return lang
    best = request.accept_languages.best_match(["lt", "en"]) if request else None
    return best or "lt"


def tr(text, lang=None):
    lang = lang or get_lang()
    return LT.get(text, text) if lang == "lt" else text
